n = int(input())

# dp[i][j] - количество лесенок из i кубиков, где нижний слой содержит НЕ БОЛЕЕ j кубиков
dp = [[0] * (n + 1) for _ in range(n + 1)]

# Базовый случай: 0 кубиков - 1 лесенка (пустая)
for j in range(n + 1):
    dp[0][j] = 1

for i in range(1, n + 1):
    for j in range(1, n + 1):
        # Не используем j как размер нижнего слоя
        dp[i][j] = dp[i][j - 1]
        
        # Используем j как размер нижнего слоя (только если i >= j)
        # Тогда следующий слой должен быть меньше j
        if i >= j:
            dp[i][j] += dp[i - j][j - 1]

print(dp[n][n])
